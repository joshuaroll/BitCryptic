#!/usr/bin/env node
// Sync design/tokens.json -> the embedded token block in scenes/art-kit.js.
//
// The art kit is a plain browser script with no fetch and no build step, so it
// carries its own copy of the tokens. A copy drifts unless something owns it:
// this script writes the block, and scripts/ci/check-art-kit.cjs fails verify if
// the block and tokens.json disagree.
//
//   node scripts/build-art-tokens.cjs          # rewrite the block
//   node scripts/build-art-tokens.cjs --check  # exit 1 if out of date
//
// Only $value survives the flatten; {a.b} aliases are resolved, so the kit never
// has to understand the DTCG format.
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const TOKENS = path.join(ROOT, 'design', 'tokens.json');
const KIT = path.join(ROOT, 'scenes', 'art-kit.js');
const OPEN = '// <art-tokens> generated by scripts/build-art-tokens.cjs from design/tokens.json. Do not edit by hand.';
const CLOSE = '// </art-tokens>';
const GROUPS = ['palette', 'light', 'outline', 'depth', 'contact', 'shadow', 'motion'];

function lookup(root, ref) {
  return ref.split('.').reduce((o, k) => (o == null ? o : o[k]), root);
}

function flatten(node, root, seen) {
  if (node && typeof node === 'object' && '$value' in node) {
    let v = node.$value;
    // An alias is a whole-string "{group.token}". Resolve through to a value.
    while (typeof v === 'string' && /^\{[^}]+\}$/.test(v)) {
      const ref = v.slice(1, -1);
      if (seen.has(ref)) throw new Error('alias cycle at ' + ref);
      seen.add(ref);
      const t = lookup(root, ref);
      if (!t) throw new Error('unresolved alias ' + v);
      v = t.$value;
    }
    return v;
  }
  if (node && typeof node === 'object' && !Array.isArray(node)) {
    const out = {};
    for (const [k, v] of Object.entries(node)) if (k[0] !== '$') out[k] = flatten(v, root, new Set());
    return out;
  }
  return node;
}

function generate() {
  const json = JSON.parse(fs.readFileSync(TOKENS, 'utf8'));
  const flat = {};
  for (const g of GROUPS) if (json[g]) flat[g] = flatten(json[g], json, new Set());
  return OPEN + '\n  var T = ' + JSON.stringify(flat) + ';\n  ' + CLOSE;
}

function currentBlock(src) {
  const a = src.indexOf(OPEN), b = src.indexOf(CLOSE);
  if (a < 0 || b < 0) return null;
  return src.slice(a, b + CLOSE.length);
}

function inSync() {
  const src = fs.readFileSync(KIT, 'utf8');
  return currentBlock(src) === generate();
}

if (require.main === module) {
  const src = fs.readFileSync(KIT, 'utf8');
  const block = currentBlock(src);
  if (!block) { console.error('art-kit.js has no <art-tokens> markers'); process.exit(1); }
  const next = generate();
  if (process.argv.includes('--check')) {
    if (block !== next) { console.error('scenes/art-kit.js tokens are stale: run node scripts/build-art-tokens.cjs'); process.exit(1); }
    console.log('art-kit tokens in sync with design/tokens.json');
  } else {
    fs.writeFileSync(KIT, src.replace(block, () => next));
    console.log(block === next ? 'art-kit tokens already in sync' : 'art-kit tokens updated from design/tokens.json');
  }
}
module.exports = { generate, inSync, OPEN, CLOSE };
